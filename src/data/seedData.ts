// Helper to generate seed POs with hierarchical approval chains
const buildSeedPo = (
  poNumber: string,
  requestId: string,
  reqNumber: string,
  supplier: Supplier,
  subtotal: number,
  status: OrderStatus,
  items: PurchaseOrderItem[],
  currentLevel: number,
  notes: string,
  trackingNumber?: string,
  carrier?: string
): PurchaseOrder => {
  const taxRate = 18.0;
  const taxAmount = subtotal * (taxRate / 100.0);
  const discountAmount = subtotal > 50000.0 ? 1500.0 : 0.0;
  const shippingCost = 600.0;
  const totalAmount = subtotal + taxAmount - discountAmount + shippingCost;

  const tier = PoApprovalWorkflowEngine.determineTier(totalAmount, INITIAL_SETTINGS);
  const steps = PoApprovalWorkflowEngine.buildApprovalChain(totalAmount, INITIAL_SETTINGS);

  // Pre-sign steps based on status
  if (status !== OrderStatus.PENDING_APPROVAL) {
    steps.forEach((s) => {
      s.isSigned = true;
      s.signerUserId = 'usr-admin';
      s.signerName = 'Vikram Malhotra';
      s.signerRole = 'Administrator';
      s.signedAt = NOW - 5 * ONE_DAY;
      s.remarks = 'Verified and authorized under enterprise procurement delegation.';
      s.signatureCertificate = PoApprovalWorkflowEngine.generateDigitalCertificate(
        poNumber,
        s.level,
        INITIAL_USERS[0],
        s.signedAt
      );
    });
  } else if (currentLevel > 1) {
    for (let i = 0; i < currentLevel - 1; i++) {
      steps[i].isSigned = true;
      steps[i].signerUserId = 'usr-mgr';
      steps[i].signerName = 'Rajesh Sharma';
      steps[i].signerRole = 'Approving Manager';
      steps[i].signedAt = NOW - 1 * ONE_DAY;
      steps[i].remarks = 'Budget cleared for project.';
      steps[i].signatureCertificate = PoApprovalWorkflowEngine.generateDigitalCertificate(
        poNumber,
        steps[i].level,
        INITIAL_USERS[2],
        steps[i].signedAt!
      );
    }
  }

  const isFullyApproved = steps.every((s) => s.isSigned);
  const nextPendingStep = steps.find((s) => !s.isSigned);

  return {
    id: `po-${poNumber.toLowerCase()}`,
    poNumber,
    purchaseRequestId: requestId,
    requestNumber: reqNumber,
    supplierId: supplier.id,
    supplierName: supplier.companyName,
    createdByUserId: 'usr-proc',
    createdByName: 'Ananya Roy',
    subtotal,
    taxRate,
    taxAmount,
    discountAmount,
    shippingCost,
    totalAmount,
    status,
    currentApprovalLevel: currentLevel,
    requiredApprovalLevel: steps.length,
    approvalTierName: `${tier.title} (${steps.length} Signatures)`,
    approvalSignaturesJson: PoApprovalWorkflowEngine.serializeSignatures(steps),
    isFullyApproved,
    pendingRoleName: nextPendingStep ? nextPendingStep.shortRoleTitle : 'Fully Authorized',
    trackingNumber,
    carrier,
    notes,
    createdAt: NOW - 6 * ONE_DAY,
    updatedAt: NOW - 1 * ONE_DAY,
    items,
  };
};

